import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const existingPath = process.env.ENV_EXISTING ?? '';
const generatedPath = process.env.ENV_GENERATED;
const mergedPath = process.env.ENV_MERGED;

if (!generatedPath || !mergedPath) {
  console.error('ENV_GENERATED and ENV_MERGED are required.');
  process.exit(1);
}

const existing = existingPath && existsSync(existingPath) ? readFileSync(existingPath, 'utf8') : '';
const existingKeys = new Set();
for (const line of existing.split(/\r?\n/)) {
  const match = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=/);
  if (match) existingKeys.add(match[1]);
}

const generated = readFileSync(generatedPath, 'utf8')
  .split(/\r?\n/)
  .map((line) => line.trim())
  .filter(Boolean);

const additions = generated.filter((line) => {
  const match = line.match(/^([A-Za-z_][A-Za-z0-9_]*)\s*=/);
  return match && !existingKeys.has(match[1]);
});

let output = existing;
if (output && !output.endsWith('\n')) output += '\n';
if (additions.length > 0) {
  output += `\n# Generated by Ultra Family OS FTP deploy at ${new Date().toISOString()}\n`;
  output += `${additions.join('\n')}\n`;
}

writeFileSync(mergedPath, output, { mode: 0o600 });
