export const translations: Record<Language, Record<TranslationKey, string>> = { ru, it };

export function translate(
  language: Language,
  key: TranslationKey,
  variables: Record<string, string | number> = {},
): string {
  const template = translations[language][key] ?? translations.ru[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    variables[name] === undefined ? match : String(variables[name]),
  );
}

export function errorMessage(language: Language, status: number): string {
  return translate(language, `error.${status}`) === `error.${status}`
    ? translate(language, 'error.generic')
    : translate(language, `error.${status}`);
}

